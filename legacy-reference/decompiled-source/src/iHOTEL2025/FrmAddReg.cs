	public string GetSIR()
	{
		int num = 1;
		DataSet dataSet = Module1.connect("select top 1 Reg_no from HT_Register where Reg_Date between '" + Conversions.ToString(Adate.Value.Month) + "/01/" + Conversions.ToString(Adate.Value.Year) + " 00:00:00' and '" + Conversions.ToString(Adate.Value.Month) + "/" + Conversions.ToString(DateTime.DaysInMonth(Adate.Value.Year, Adate.Value.Month)) + "/" + Conversions.ToString(Adate.Value.Year) + " 23:59:59' order by Reg_no Desc");
		checked
		{
			if (dataSet.Tables[0].Rows.Count == 0)
			{
				num = 1;
			}
			else
			{
				num = Conversions.ToInteger(dataSet.Tables[0].Rows[0]["Reg_no"].ToString().Substring(dataSet.Tables[0].Rows[0]["Reg_no"].ToString().LastIndexOf("-") + 1));
				num++;
			}
			return Strings.Format(DateTime.Now, "REGyyMM") + "-" + Strings.Format(num, "0000");
		}
	}

